#!/usr/bin/env python3
"""gen_sprite - make the rider sprite of the Turns page.

The sprite is a snowboard seen from above, with the rider on it. It moves along the
turn line on the Turns page (D-29). The device does not rotate images at run time.
This script therefore draws one frame for each of 16 directions, as a sprite sheet.

Frame 0 points right (+x). Each next frame turns 22.5 degrees clockwise on the screen,
where y grows down. main/ui/turn_view.c picks the frame from the direction of the line.

Output, in assets/sprites:
  heygo_sprites.h          The declarations.
  heygo_board_sprite.c     16 LVGL images, ARGB8888 (B, G, R, A in memory), 20 x 20 px.
  heygo_board_sprite.png   A preview at 4x scale.

Run: python3 assets/tools/gen_sprite.py  (needs Pillow)
"""
from pathlib import Path

from PIL import Image, ImageDraw

SIZE = 20          # Pixels on the screen.
SS = 8             # Supersampling.
FRAMES = 16
OUT = Path(__file__).resolve().parent.parent / "sprites"

INK = (255, 255, 255, 255)      # Board: white, so it shows on the accent line.
EDGE = (10, 10, 10, 255)        # Outline: the screen background.
ACCENT = (177, 254, 43, 255)    # Brand lime #B1FE2B.


def frame0():
    """One frame that points right, at SS times the size."""
    s = SIZE * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c = s / 2
    # The board: a capsule 18 x 7 px along the direction of travel, with a dark outline.
    bl, bw, o = 18 * SS, 7 * SS, 1 * SS
    d.rounded_rectangle((c - bl / 2, c - bw / 2, c + bl / 2, c + bw / 2), radius=bw / 2, fill=EDGE)
    d.rounded_rectangle((c - bl / 2 + o, c - bw / 2 + o, c + bl / 2 - o, c + bw / 2 - o), radius=bw / 2 - o, fill=INK)
    # The rider stands sideways on the board: the shoulders lie along the board.
    sl, sw = 10 * SS, 5 * SS
    d.ellipse((c - sl / 2, c - sw / 2, c + sl / 2, c + sw / 2), fill=EDGE)
    # The head, in the brand color.
    h = 2.5 * SS
    d.ellipse((c - h, c - h, c + h, c + h), fill=ACCENT)
    # The nose of the board: a small dark mark at the front shows the direction.
    n = 1.5 * SS
    nx = c + bl / 2 - 3.2 * SS
    d.ellipse((nx - n, c - n, nx + n, c + n), fill=EDGE)
    return img


def frames():
    big = frame0()
    out = []
    for k in range(FRAMES):
        # PIL turns counterclockwise for a positive angle. The screen turns clockwise.
        f = big.rotate(-22.5 * k, resample=Image.BICUBIC)
        out.append(f.resize((SIZE, SIZE), Image.LANCZOS))
    return out


def write(imgs):
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for k, img in enumerate(imgs):
        data = []
        for r, g, b, a in img.getdata():
            data += [b, g, r, a]
        lines = [", ".join(f"0x{v:02x}" for v in data[i:i + 16]) for i in range(0, len(data), 16)]
        rows.append(f"    /* frame {k} */\n    " + ",\n    ".join(lines))
    c = [
        "/* assets/sprites/heygo_board_sprite.c",
        " * Generated by assets/tools/gen_sprite.py. Do not edit.",
        " * 16 frames of the rider sprite, 20 x 20 px, ARGB8888. Frame 0 points right,",
        " * and each next frame turns 22.5 degrees clockwise. */",
        '#include "heygo_sprites.h"',
        "",
        f"static const uint8_t s_map[{FRAMES}][{SIZE * SIZE * 4}] = {{",
        ",\n".join("    {\n" + r + "\n    }" for r in rows),
        "};",
        "",
        "#define FRAME(k) { .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, \\",
        f"                         .w = {SIZE}, .h = {SIZE}, .stride = {SIZE * 4} }}, \\",
        f"                  .data_size = {SIZE * SIZE * 4}, .data = s_map[k] }}",
        "",
        f"const lv_image_dsc_t heygo_board_sprite[HEYGO_SPRITE_FRAMES] = {{",
        "    " + ", ".join(f"FRAME({k})" for k in range(FRAMES)),
        "};",
        "",
    ]
    (OUT / "heygo_board_sprite.c").write_text("\n".join(c), encoding="utf-8")
    h = [
        "/* assets/sprites/heygo_sprites.h",
        " * Declares the generated sprites. assets/tools/gen_sprite.py makes them.",
        " *",
        " *   heygo_board_sprite  The rider of the Turns page. 16 frames of 20 x 20 px.",
        " *                       Frame 0 points right. Each next frame turns 22.5 degrees",
        " *                       clockwise on the screen. */",
        "#pragma once",
        "",
        '#include "lvgl.h"',
        "",
        f"#define HEYGO_SPRITE_FRAMES {FRAMES}",
        f"#define HEYGO_SPRITE_SIZE   {SIZE}",
        "",
        "extern const lv_image_dsc_t heygo_board_sprite[HEYGO_SPRITE_FRAMES];",
        "",
    ]
    (OUT / "heygo_sprites.h").write_text("\n".join(h), encoding="utf-8")
    # Preview: the 16 frames on the screen background and on the accent color, at 4x.
    sc, gap = 4, 4
    w = FRAMES * (SIZE * sc + gap) + gap
    prev = Image.new("RGB", (w, 2 * (SIZE * sc + gap) + gap), (40, 40, 40))
    for row, bg in enumerate([(0, 0, 0), (177, 254, 43)]):
        for k, img in enumerate(imgs):
            tile = Image.new("RGBA", (SIZE, SIZE), bg + (255,))
            tile.alpha_composite(img)
            prev.paste(tile.convert("RGB").resize((SIZE * sc, SIZE * sc), Image.NEAREST),
                       (gap + k * (SIZE * sc + gap), gap + row * (SIZE * sc + gap)))
    prev.save(OUT / "heygo_board_sprite.png")
    print(f"Wrote {FRAMES} frames to {OUT}")


if __name__ == "__main__":
    write(frames())

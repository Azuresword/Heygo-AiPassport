#!/usr/bin/env python3
"""gen_boot_logo - make the LVGL images of the boot logo (D-35).

Input: assets/brand/logo_<part>.png and assets/brand/logo_parts.json, from
assets/tools/fetch_figma_logo.py.

The logo is one color, so each part keeps only its alpha channel (LVGL A8). The device
sets the color with the image recolor style. A8 uses a quarter of the Flash of ARGB8888.

Output, in assets/sprites:
  heygo_logo.h    The declarations: one image and one place for each part.
  heygo_logo.c    The A8 data of the six parts.

Run: python3 assets/tools/gen_boot_logo.py  (needs Pillow)
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "brand"
OUT = ROOT / "sprites"
ORDER = ["h", "e", "y", "g", "o", "board"]


def main():
    meta = json.loads((BRAND / "logo_parts.json").read_text())
    parts = meta["parts"]
    c = ["/* assets/sprites/heygo_logo.c",
         " * Generated by assets/tools/gen_boot_logo.py. Do not edit.",
         f" * The Heygo logo of the boot screen, {meta['width']} x {meta['height']} px, in six A8 parts.",
         f" * Source: {meta['source']}. */",
         '#include "heygo_logo.h"', ""]
    total = 0
    for name in ORDER:
        img = Image.open(BRAND / f"logo_{name}.png").convert("RGBA")
        w, h = img.size
        assert (w, h) == (parts[name]["w"], parts[name]["h"]), name
        alpha = img.getchannel("A").tobytes()
        total += len(alpha)
        c.append(f"static const uint8_t s_{name}[{len(alpha)}] = {{")
        for i in range(0, len(alpha), 24):
            c.append("    " + ", ".join(f"0x{b:02x}" for b in alpha[i:i + 24]) + ",")
        c.append("};")
        c.append("")
    c.append("const heygo_logo_part_t heygo_logo_parts[HEYGO_LOGO_PARTS] = {")
    for name in ORDER:
        p = parts[name]
        c.append(f"    {{ .x = {p['x']}, .y = {p['y']}, .img = {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, "
                 f".cf = LV_COLOR_FORMAT_A8, .w = {p['w']}, .h = {p['h']}, .stride = {p['w']} }}, "
                 f".data_size = {p['w'] * p['h']}, .data = s_{name} }} }},")
    c.append("};")
    c.append("")
    (OUT / "heygo_logo.c").write_text("\n".join(c))

    h = ["/* assets/sprites/heygo_logo.h",
         " * Generated by assets/tools/gen_boot_logo.py. Do not edit.",
         " * The Heygo logo of the boot screen (D-35), in six A8 parts. Each part has its",
         " * place in the wordmark. Set the color with the image recolor style. */",
         "#pragma once", "", '#include "lvgl.h"', "",
         f"#define HEYGO_LOGO_WIDTH  {meta['width']}",
         f"#define HEYGO_LOGO_HEIGHT {meta['height']}",
         f"#define HEYGO_LOGO_PARTS {len(ORDER)}", "",
         "// The parts, in this order.",
         "enum { " + ", ".join(f"HEYGO_LOGO_{n.upper()}" for n in ORDER) + " };", "",
         "typedef struct {",
         "    int16_t x, y;            // The top-left corner in the wordmark.",
         "    lv_image_dsc_t img;",
         "} heygo_logo_part_t;", "",
         "extern const heygo_logo_part_t heygo_logo_parts[HEYGO_LOGO_PARTS];", ""]
    (OUT / "heygo_logo.h").write_text("\n".join(h))
    print(f"Wrote heygo_logo.c and heygo_logo.h: {len(ORDER)} parts, {total} bytes of A8 data")


if __name__ == "__main__":
    main()

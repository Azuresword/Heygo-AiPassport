def check_glyphs(script):
    have = set((ASSETS / "fonts" / "heygo_sc_16.chars.txt").read_text(encoding="utf-8"))
    missing = set()
    for _, _, sets in script:
        for k, v in sets.items():
            if isinstance(v, str) and k not in ("link_state", "icon_state"):
                missing |= {c for c in v if c not in have}
    return sorted(missing)


def to_png(raw_path):
    data = raw_path.read_bytes()
    img = Image.new("RGB", (HOR, VER))
    px = img.load()
    for i in range(HOR * VER):
        v = data[2 * i] | (data[2 * i + 1] << 8)
        r, g, b = (v >> 11) & 0x1F, (v >> 5) & 0x3F, v & 0x1F
        px[i % HOR, i // HOR] = ((r * 527 + 23) >> 6, (g * 259 + 33) >> 6, (b * 527 + 23) >> 6)
    return img


def write_pngs(script, raw_dir, out):
    out.mkdir(parents=True, exist_ok=True)
    images = []
    for name, _, _ in script:
        img = to_png(raw_dir / f"{name}.rgb565")
        img.save(out / f"{name}.png")
        images.append((name, img))

    # Contact sheet at 2x so a reviewer can read the 16 px text.
    scale, gap, cap = 2, 24, 28
    cols = 5
    rows = (len(images) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * (HOR * scale + gap) + gap,
                              rows * (VER * scale + gap + cap) + gap), (245, 245, 245))
    draw = ImageDraw.Draw(sheet)
    for i, (name, img) in enumerate(images):
        x = gap + (i % cols) * (HOR * scale + gap)
        y = gap + (i // cols) * (VER * scale + gap + cap)
        draw.text((x, y), name, fill=(40, 40, 40))
        sheet.paste(img.resize((HOR * scale, VER * scale), Image.NEAREST), (x, y + cap))
    sheet.save(out / "contact-sheet.png")
    print(f"Wrote {len(images)} PNG files and contact-sheet.png to {out}")


def layout_problems(name, boxes):
    probs = []
    for wid, (x, y, w, h) in boxes.items():
        if h <= 0:
            continue
        if x < 0 or y < 0 or x + w > HOR or y + h > VER:
            probs.append(f"{name}: {wid} leaves the screen ({x},{y},{w},{h})")
    items = [(k, v) for k, v in boxes.items() if v[3] > 0]
    for i, (a, (ax, ay, aw, ah)) in enumerate(items):
        for b, (bx, by, bw, bh) in items[i + 1:]:
            if ax < bx + bw and bx < ax + aw and ay < by + bh and by < ay + ah:
                probs.append(f"{name}: {a} overlaps {b} "
                             f"(y {ay}..{ay + ah - 1} and {by}..{by + bh - 1})")
    return probs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdkconfig", type=Path, default=FW / "sdkconfig")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    out = args.out.resolve()

    strings = {k: v["zh"] for k, v in
               json.loads((ASSETS / "ui" / "strings.json").read_text(encoding="utf-8"))["strings"].items()}
    script = frames(strings)
    missing = check_glyphs(script)
    if missing:
        sys.exit("ERROR: sample text has glyphs that heygo_sc_16 lacks: " + "".join(missing))

    flow = json.loads((FW / "flows" / "coach.flow.json").read_text(encoding="utf-8"))
    sys.path.insert(0, str(FW / "tools" / "flow"))
    import flowc
    flow_report = flowc.validate(flow, "flows/coach.flow.json")
    exe = build(args.sdkconfig.resolve())
    raw_dir = BUILD / "frames"
    raw_dir.mkdir(parents=True, exist_ok=True)
    cmds = []
    for name, screen, sets in script:
        if screen:
            cmds.append(f"screen {screen}")
        if screen == "coach":
            cmds.append("mem coach_built")
        cmds += [f"label {k[1:]} {v}" if k.startswith("@") else f"panel {v}" if k == "!panel" else f"set {k} {v}"
                 for k, v in sets.items()]
        cmds.append(f"snap {name}")
    # The body subject holds BODY_SIZE - 1 bytes. One ASCII byte in front of
    # 3-byte characters puts a plain cut inside a character.
    global cut_test
    cut_test = "A" + "滑" * 100
    cmds += ["screen coach", f"set body_text {cut_test}", "text body"]
    # Run every frame twice. The first pass makes LVGL's one-time allocations.
    # A second pass that ends higher than the first shows a leak.
    cmds = cmds + ["drop", "mem cycle1"] + cmds + ["drop", "mem cycle2"]
    r = subprocess.run([str(exe), str(raw_dir)], input="\n".join(cmds) + "\n",
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"ERROR: render exited {r.returncode}\n{r.stdout}\n{r.stderr}")

    boxes, mem, problems, cur, lock, text = {}, {}, [], None, None, None
    for line in r.stdout.splitlines():
        tag, _, rest = line.partition(" ")
        if tag == "ERR":
            problems.append(rest)
        elif tag == "SNAP":
            cur = rest
            boxes[cur] = {}
        elif tag == "BOX":
            wid, *kv = rest.split()
            boxes[cur][wid] = tuple(int(p.split("=")[1]) for p in kv)
        elif tag == "MEM":
            label, *kv = rest.split()
            mem.setdefault(label, dict(p.split("=") for p in kv))  # keep pass 1
        elif tag == "TEXT" and text is None:
            n, _, hexed = rest.partition(" ")
            text = bytes.fromhex(hexed)
        elif tag == "LOCK":
            lock = dict(p.split("=") for p in rest.split())

    for name, _, _ in script:
        problems += layout_problems(name, boxes.get(name, {}))
    if Image is None:
        print("PNG output: SKIPPED (this Python has no Pillow)")
    else:
        write_pngs(script, raw_dir, out)

    base = int(mem["after_display"]["used"])
    built = int(mem["coach_built"]["used"])
    peak = max(int(m["peak"]) for m in mem.values())
    total = int(mem["after_display"]["total"])
    print(f"LVGL pool: total {total} B")
    print(f"  after display        {base} B")
    print(f"  coach screen built   {built} B  (screen cost {built - base} B)")
    print(f"  flowc estimate       {flow_report['pool_estimate']} B for all screens")
    for name, _, _ in script:
        print(f"  {name:<20} used {mem[name]['used']} B, biggest free {mem[name]['biggest_free']} B")
    print(f"  peak during run      {peak} B of {total} B ({100 * peak // total}%)")
    for name, b in boxes.items():
        if "body" in b:
            print(f"  {name:<20} body h={b['body'][3]}")
    body_size = next(x["size"] for x in flow["subjects"] if x["id"] == "body_text")
    try:
        text.decode("utf-8")
        cut_ok = text is not None and body_size - 4 < len(text) < body_size
    except (UnicodeDecodeError, AttributeError):
        cut_ok = False
    if cut_ok:
        print(f"UTF-8 cut: {len(cut_test.encode())} B text stored as {len(text)} B, "
              f"subject size {body_size}")
    else:
        tail = text[-4:] if text else text
        problems.append(f"UTF-8 cut failed: stored {len(text or b'')} B ending {tail!r}")
    if not lock or lock["takes"] != lock["gives"] or int(lock["takes"]) == 0:
        problems.append(f"lock hooks not balanced: {lock}")
    else:
        print(f"Lock hooks: {lock['takes']} takes, {lock['gives']} gives")
    print(f"  after pass 1 / pass 2 {mem['cycle1']['used']} B / {mem['cycle2']['used']} B")
    leaked = int(mem["cycle2"]["used"]) - int(mem["cycle1"]["used"])
    if leaked > 0:
        problems.append(f"pass 2 ends {leaked} B above pass 1: the LVGL pool leaks")
    if problems:
        print("Layout: FAIL")
        for p in problems:
            print("  " + p)
        return 1
    print("Layout: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())

def check_glyphs(script):
    have = set((ASSETS / "fonts" / "heygo_sc_16.chars.txt").read_text(encoding="utf-8"))
    missing = set()
    for _, _, sets in script:
        for k, v in sets.items():
            if isinstance(v, str) and k not in ("link_state", "icon_state", "!shape"):
                missing |= {c for c in v if c not in have}
    return sorted(missing)


# The popup entry animation (D-31), for assets/mockups/popup-anim.gif. The live data page shows
# first. Then the four kinds come one after the other, each as a new popup, as on the device.

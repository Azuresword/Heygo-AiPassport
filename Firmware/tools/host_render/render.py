#!/usr/bin/env python3
"""Draw the generated coach screens on the host with the device LVGL settings.

The script:
  1. Makes an LVGL settings header from the device sdkconfig.
  2. Compiles LVGL, the generated screens, and the Chinese fonts for the host.
  3. Draws each P0 screen state with the texts from assets/ui/strings.json.
  4. Writes PNG files to assets/mockups and reports the LVGL pool use.

PNG output needs Pillow. Without Pillow the script runs the checks only.

It fails when a sample text has a glyph that the font does not have, when a
widget leaves the screen, when two widgets overlap, when the setters do not
take and give the lock in pairs, when a second pass ends with more pool use
than the first pass, or when a setter cuts a text inside a UTF-8 character.

Usage:
  python3 tools/host_render/render.py [--sdkconfig PATH] [--out DIR]

  --sdkconfig  Device settings file. Default: sdkconfig (run idf.py build once first).
  --out        Folder for the PNG files. Default: ../assets/mockups.
"""

import argparse
import json
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

try:
    from PIL import Image, ImageDraw
except ImportError:  # The ESP-IDF Python has no Pillow. The checks still run.
    Image = None

HERE = Path(__file__).resolve().parent
FW = HERE.parent.parent
REPO = FW.parent
ASSETS = REPO / "assets"
LVGL = FW / "managed_components" / "lvgl__lvgl"
BUILD = FW / "build" / "host_render"
OUT = ASSETS / "mockups"
HOR, VER = 240, 320

CC = os.environ.get("CC", "cc")
CFLAGS = ["-O1", "-g0", "-w", "-DLV_CONF_SKIP",
          '-DLV_CONF_KCONFIG_EXTERNAL_INCLUDE="lv_sdkconfig.h"',
          f"-I{BUILD}", f"-I{LVGL}"]


def sdkconfig_header(src):
    if not src.exists():
        sys.exit(f"ERROR: {src} is missing. Run idf.py build once first.")
    lines = ["// Generated by tools/host_render/render.py from sdkconfig.", "#pragma once"]
    for raw in src.read_text().splitlines():
        m = re.match(r"^(CONFIG_LV_[A-Z0-9_]+)=(.*)$", raw)
        if m:
            value = "1" if m.group(2) == "y" else m.group(2)
            lines.append(f"#define {m.group(1)} {value}")
    BUILD.mkdir(parents=True, exist_ok=True)
    out = BUILD / "lv_sdkconfig.h"
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out


def compile_one(src, obj, extra, stamp):
    if obj.exists() and obj.stat().st_mtime > max(src.stat().st_mtime, stamp):
        return None
    obj.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([CC, *CFLAGS, *extra, "-c", str(src), "-o", str(obj)],
                       capture_output=True, text=True)
    return None if r.returncode == 0 else f"{src}:\n{r.stderr}"


def build(sdkconfig):
    stamp = sdkconfig_header(sdkconfig).stat().st_mtime
    # An object file also depends on the headers. A changed screen struct in a generated
    # header with an old render.o crashed the renderer, so a newer header rebuilds the app.
    headers = list((FW / "main" / "generated").glob("*.h")) + list((FW / "main" / "ui").glob("*.h")) + \
        [ASSETS / "fonts" / "heygo_fonts.h"]
    app_stamp = max([stamp] + [h.stat().st_mtime for h in headers])
    jobs = [(s, BUILD / "lvgl" / s.relative_to(LVGL).with_suffix(".o"), [])
            for s in sorted((LVGL / "src").rglob("*.c"))]
    app_inc = [f"-I{FW / 'main' / d}" for d in ("ui", "generated")] + [f"-I{ASSETS / 'fonts'}"]
    app_src = [HERE / "render.c", FW / "main/ui/ui_theme.c",
               FW / "main/ui/ui_state_icon.c",
               FW / "main/generated/coach_screens.c", FW / "main/generated/coach_bindings.c",
               ASSETS / "fonts/heygo_sc_16.c", ASSETS / "fonts/heygo_sc_28.c",
               ASSETS / "fonts/heygo_display_20.c", ASSETS / "fonts/heygo_display_34.c",
               ASSETS / "fonts/heygo_display_48.c"]
    lvgl_jobs = len(jobs)
    jobs += [(s, BUILD / "app" / (s.stem + ".o"), app_inc) for s in app_src]
    with ThreadPoolExecutor(os.cpu_count() or 4) as pool:
        errors = [e for e in pool.map(
            lambda ij: compile_one(ij[1][0], ij[1][1], ij[1][2], stamp if ij[0] < lvgl_jobs else app_stamp),
            enumerate(jobs)) if e]
    if errors:
        sys.exit("ERROR: compile failed\n" + errors[0])
    exe = BUILD / "render"
    r = subprocess.run([CC, *[str(j[1]) for j in jobs], "-lm", "-o", str(exe)],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit("ERROR: link failed\n" + r.stderr)
    return exe


